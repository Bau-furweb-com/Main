function applyLanguage(lang) {
  const dict = translations[lang] || translations.en;

  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });

  localStorage.setItem("siteLang", lang);
}

function setupLanguageSwitch() {
  const saved = localStorage.getItem("siteLang");
  const initial = saved || "de";

  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.addEventListener("click", () => applyLanguage(btn.dataset.lang));
  });

  applyLanguage(initial);

  const year = document.querySelector("[id^='year-']");
  if (year) {
    year.textContent = new Date().getFullYear();
  }
}

function setupHomeHeroScroll() {
  if (!document.body.classList.contains("home-page")) {
    return;
  }

  const maxScroll = 200;
  let ticking = false;

  const applyProgress = () => {
    const raw = window.scrollY / maxScroll;
    const progress = Math.max(0, Math.min(raw, 1));
    document.body.style.setProperty("--hero-progress", progress.toFixed(4));
    ticking = false;
  };

  const onScroll = () => {
    if (ticking) {
      return;
    }
    ticking = true;
    window.requestAnimationFrame(applyProgress);
  };

  applyProgress();
  window.addEventListener("scroll", onScroll, { passive: true });
  window.addEventListener("resize", onScroll, { passive: true });
}

function setupMobileMenu() {
  const toggle = document.querySelector(".menu-toggle");
  const overlay = document.querySelector(".mobile-overlay");
  let closeTimer = null;
  let touchStartY = 0;
  let touchStartX = 0;

  if (!toggle || !overlay) {
    return;
  }

  const closeMenu = (instant = false) => {
    if (closeTimer) {
      window.clearTimeout(closeTimer);
      closeTimer = null;
    }

    if (instant || !overlay.classList.contains("open")) {
      overlay.classList.remove("open", "closing");
      document.body.classList.remove("menu-open");
      toggle.classList.remove("open");
      toggle.setAttribute("aria-expanded", "false");
      overlay.setAttribute("aria-hidden", "true");
      return;
    }

    overlay.classList.add("closing");
    overlay.classList.remove("open");
    document.body.classList.remove("menu-open");
    toggle.classList.remove("open");
    toggle.setAttribute("aria-expanded", "false");
    overlay.setAttribute("aria-hidden", "true");

    closeTimer = window.setTimeout(() => {
      overlay.classList.remove("closing");
      closeTimer = null;
    }, 520);
  };

  const openMenu = () => {
    if (closeTimer) {
      window.clearTimeout(closeTimer);
      closeTimer = null;
    }

    overlay.classList.remove("closing");
    document.body.classList.add("menu-open");
    toggle.classList.add("open");
    overlay.classList.add("open");
    toggle.setAttribute("aria-expanded", "true");
    overlay.setAttribute("aria-hidden", "false");
  };

  toggle.addEventListener("click", () => {
    if (overlay.classList.contains("open")) {
      closeMenu();
    } else {
      openMenu();
    }
  });

  overlay.addEventListener("click", (event) => {
    if (event.target === overlay) {
      closeMenu();
    }
  });

  overlay.addEventListener(
    "touchstart",
    (event) => {
      if (!overlay.classList.contains("open") || event.touches.length !== 1) {
        return;
      }
      touchStartY = event.touches[0].clientY;
      touchStartX = event.touches[0].clientX;
    },
    { passive: true }
  );

  overlay.addEventListener(
    "touchend",
    (event) => {
      if (!overlay.classList.contains("open") || event.changedTouches.length !== 1) {
        return;
      }

      const touchEndY = event.changedTouches[0].clientY;
      const touchEndX = event.changedTouches[0].clientX;
      const deltaY = touchEndY - touchStartY;
      const deltaX = Math.abs(touchEndX - touchStartX);

      // Close on clear downward swipe while filtering accidental diagonal gestures.
      if (deltaY > 90 && deltaY > deltaX) {
        closeMenu();
      }
    },
    { passive: true }
  );

  overlay.querySelectorAll("a, .lang-switch button").forEach((el) => {
    el.addEventListener("click", () => {
      closeMenu();
    });
  });

  window.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && overlay.classList.contains("open")) {
      closeMenu();
    }
  });

  window.addEventListener("resize", () => {
    if (window.innerWidth > 900 && overlay.classList.contains("open")) {
      closeMenu(true);
    }
  });
}

window.addEventListener("DOMContentLoaded", () => {
  setupLanguageSwitch();
  setupHomeHeroScroll();
  setupMobileMenu();
});
