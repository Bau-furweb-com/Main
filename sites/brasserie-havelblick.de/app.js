let blogDataCache = null;

function renderMenu(lang) {
  const data = menuData[lang] || menuData.de;
  const speiseList = document.querySelector("#speise-list");
  const abendList = document.querySelector("#abend-list");
  if (!speiseList || !abendList) return;

  const renderItems = (target, items) => {
    target.innerHTML = "";
    const perColumn = 5;
    const columns = Math.ceil(items.length / perColumn);

    for (let i = 0; i < columns; i += 1) {
      const chunk = items.slice(i * perColumn, (i + 1) * perColumn);
      const column = document.createElement("section");
      column.className = "menu-column";
      column.innerHTML = `<h3 class="menu-column-title">${lang === "de" ? "Auswahl" : "Selection"} ${i + 1}</h3>`;

      chunk.forEach((item) => {
        const article = document.createElement("article");
        article.className = "menu-item";
        article.innerHTML = `
          <div class="menu-item-head">
            <h3>${item.name}</h3>
            <span class="price">${item.price}</span>
          </div>
          <p>${item.desc}</p>
        `;
        column.appendChild(article);
      });

      target.appendChild(column);
    }
  };

  renderItems(speiseList, data.speise);
  renderItems(abendList, data.abend);
}

async function renderBlogFromJson(lang) {
  const list = document.querySelector("#blog-list");
  if (!list) return;

  if (!blogDataCache) {
    try {
      const response = await fetch("data/blog.json", { cache: "no-store" });
      if (!response.ok) {
        throw new Error("Failed to load blog json");
      }
      blogDataCache = await response.json();
    } catch (_err) {
      list.innerHTML = `<article class="card blog-card"><p>${lang === "de" ? "Blogdaten konnten nicht geladen werden." : "Blog data could not be loaded."}</p></article>`;
      return;
    }
  }

  const locale = lang === "de" ? "de-DE" : "en-US";
  const posts = Array.isArray(blogDataCache) ? blogDataCache : [];
  list.innerHTML = "";

  posts.forEach((post) => {
    const title = post?.title?.[lang] || post?.title?.de || "";
    const text = post?.description?.[lang] || post?.description?.de || "";
    const date = post?.postedAt ? new Date(post.postedAt).toLocaleDateString(locale, { day: "2-digit", month: "short", year: "numeric" }) : "";
    const image = post?.image || "";
    const card = document.createElement("article");
    card.className = "card blog-card";
    card.innerHTML = `
      <img src="${image}" alt="${title}">
      <p class="meta">${date}</p>
      <h3>${title}</h3>
      <p>${text}</p>
    `;
    list.appendChild(card);
  });
}

function applyLanguage(lang) {
  const dict = translations[lang] || translations.de;
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll("[data-i18n-content]").forEach((el) => {
    const key = el.getAttribute("data-i18n-content");
    if (dict[key]) {
      el.setAttribute("content", dict[key]);
    }
  });

  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });

  renderMenu(lang);
  renderBlogFromJson(lang);
  localStorage.setItem("siteLang", lang);
}

function setupLanguageSwitch() {
  const initial = localStorage.getItem("siteLang") || "de";
  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.addEventListener("click", () => applyLanguage(btn.dataset.lang));
  });
  applyLanguage(initial);

  const yearNode = document.querySelector("[data-year]");
  if (yearNode) {
    yearNode.textContent = String(new Date().getFullYear());
  }
}

function setupMobileMenu() {
  const toggle = document.querySelector(".menu-toggle");
  const overlay = document.querySelector(".mobile-overlay");
  if (!toggle || !overlay) return;

  toggle.addEventListener("click", () => {
    const open = overlay.classList.toggle("open");
    toggle.classList.toggle("open", open);
    toggle.setAttribute("aria-expanded", String(open));
  });

  overlay.addEventListener("click", (event) => {
    if (event.target === overlay) {
      overlay.classList.remove("open");
      toggle.classList.remove("open");
      toggle.setAttribute("aria-expanded", "false");
    }
  });

  overlay.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      overlay.classList.remove("open");
      toggle.classList.remove("open");
      toggle.setAttribute("aria-expanded", "false");
    });
  });
}

function setupMenuTabs() {
  const tabs = Array.from(document.querySelectorAll(".menu-tab"));
  const panels = Array.from(document.querySelectorAll(".menu-panel"));
  const mobileSelect = document.querySelector("#menu-mobile-select");
  if (!tabs.length || !panels.length) return;

  const setTarget = (target) => {
    tabs.forEach((t) => t.classList.toggle("active", t.getAttribute("data-menu-target") === target));
    panels.forEach((panel) => panel.classList.toggle("active", panel.getAttribute("data-menu-panel") === target));
    if (mobileSelect) {
      mobileSelect.value = target;
    }
  };

  tabs.forEach((tab) => {
    tab.addEventListener("click", () => {
      setTarget(tab.getAttribute("data-menu-target"));
    });
  });

  if (mobileSelect) {
    mobileSelect.addEventListener("change", () => setTarget(mobileSelect.value));
  }
}

function setupGalleryAutoScroll() {
  if (window.matchMedia("(min-width: 701px)").matches) {
    return;
  }

  const tracks = Array.from(document.querySelectorAll(".gallery-track"));
  if (!tracks.length) {
    return;
  }

  tracks.forEach((track) => {
    const slides = Array.from(track.querySelectorAll(".gallery-photo"));
    if (slides.length < 2) {
      return;
    }

    let index = 0;
    window.setInterval(() => {
      index = (index + 1) % slides.length;
      track.scrollTo({ left: track.clientWidth * index, behavior: "smooth" });
    }, 3200);
  });
}

function setupReveal() {
  const nodes = Array.from(document.querySelectorAll(".reveal"));
  if (!nodes.length) return;

  const observer = new IntersectionObserver(
    (entries, obs) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          obs.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.15 }
  );

  nodes.forEach((node) => observer.observe(node));
}

function setActiveNav() {
  const page = document.body.getAttribute("data-page");
  if (!page) return;
  document.querySelectorAll(`[data-page-link="${page}"]`).forEach((item) => {
    item.classList.add("active");
  });
}

document.addEventListener("DOMContentLoaded", () => {
  setupLanguageSwitch();
  setupMobileMenu();
  setupMenuTabs();
  setupGalleryAutoScroll();
  setupReveal();
  setActiveNav();
});
