function setupCarousels() {
  const carousels = [...document.querySelectorAll("[data-carousel]")];
  if (!carousels.length) return;

  carousels.forEach((carousel) => {
    const slides = [...carousel.querySelectorAll(".carousel-slide")];
    if (slides.length < 2) return;

    const prev = carousel.querySelector(".carousel-btn.prev");
    const next = carousel.querySelector(".carousel-btn.next");
    const dotsHost = carousel.querySelector(".carousel-dots");
    const interval = Number(carousel.getAttribute("data-interval") || 3600);
    let dots = [];

    let index = slides.findIndex((slide) => slide.classList.contains("is-active"));
    if (index < 0) index = 0;

    const setActive = (newIndex) => {
      index = (newIndex + slides.length) % slides.length;
      slides.forEach((slide, i) => {
        slide.classList.toggle("is-active", i === index);
      });
      dots.forEach((dot, i) => {
        dot.classList.toggle("is-active", i === index);
      });
    };

    const goNext = () => setActive(index + 1);
    const goPrev = () => setActive(index - 1);

    if (next) next.addEventListener("click", goNext);
    if (prev) prev.addEventListener("click", goPrev);

    if (dotsHost) {
      dotsHost.innerHTML = "";
      dots = slides.map((_slide, dotIndex) => {
        const dot = document.createElement("button");
        dot.type = "button";
        dot.className = "carousel-dot";
        dot.setAttribute("aria-label", "Slide " + String(dotIndex + 1));
        dot.addEventListener("click", () => setActive(dotIndex));
        dotsHost.appendChild(dot);
        return dot;
      });
    }

    setActive(index);

    let timerId = window.setInterval(goNext, interval);
    carousel.addEventListener("mouseenter", () => {
      window.clearInterval(timerId);
    });
    carousel.addEventListener("mouseleave", () => {
      timerId = window.setInterval(goNext, interval);
    });
  });
}

function setupRowLimitedGrid(gridId, moreBtnId) {
  const grid = byId(gridId);
  const moreBtn = byId(moreBtnId);
  if (!grid || !moreBtn) return;

  const items = [...grid.children];
  if (!items.length) {
    moreBtn.style.display = "none";
    return;
  }
  const rows = Number(grid.getAttribute("data-rows") || 4);

  const getColumnCount = () => {
    const template = window.getComputedStyle(grid).gridTemplateColumns;
    if (!template) return 1;
    const columns = template.split(" ").filter(Boolean).length;
    return columns > 0 ? columns : 1;
  };

  const update = () => {
    const columns = getColumnCount();
    const expanded = Boolean(rowGridExpandedStates[gridId]);
    const visibleCount = expanded ? items.length : Math.min(items.length, columns * rows);

    items.forEach((item, idx) => {
      item.style.display = idx < visibleCount ? "" : "none";
    });

    moreBtn.style.display = expanded || visibleCount >= items.length ? "none" : "inline-flex";
  };

  moreBtn.addEventListener("click", () => {
    rowGridExpandedStates[gridId] = true;
    update();
  });

  window.addEventListener("resize", update, { passive: true });
  update();
}

