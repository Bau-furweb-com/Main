function setupHiringPopup() {
  let lastSeen = 0;
  try {
    lastSeen = Number(localStorage.getItem(HIRING_POPUP_KEY) || 0);
  } catch (_err) {
    lastSeen = 0;
  }

  if (Date.now() - lastSeen < HIRING_POPUP_INTERVAL_MS) return;

  let modal = byId("hiringPopup");
  if (!modal) {
    modal = document.createElement("section");
    modal.id = "hiringPopup";
    modal.className = "hiring-popup";
    modal.setAttribute("aria-hidden", "true");
    modal.innerHTML =
      '<article class="hiring-popup-panel">' +
      '<h2 id="hiringPopupTitle"></h2>' +
      '<p id="hiringPopupText"></p>' +
      '<div class="hiring-popup-actions">' +
      '<a id="hiringPopupCta" class="btn btn-primary" href="jobs.html"></a>' +
      '<button id="hiringPopupClose" class="btn btn-secondary" type="button"></button>' +
      "</div>" +
      "</article>";
    document.body.appendChild(modal);
  }

  const close = () => {
    modal.classList.remove("open");
    modal.setAttribute("aria-hidden", "true");
    document.body.style.overflow = "";
    try {
      localStorage.setItem(HIRING_POPUP_KEY, String(Date.now()));
    } catch (_err) {}
  };

  const cta = byId("hiringPopupCta");
  const closeBtn = byId("hiringPopupClose");
  if (cta) cta.addEventListener("click", close);
  if (closeBtn) closeBtn.addEventListener("click", close);
  modal.addEventListener("click", (event) => {
    if (event.target === modal) close();
  });

  updateHiringPopupText();
  modal.classList.add("open");
  modal.setAttribute("aria-hidden", "false");
  document.body.style.overflow = "hidden";
}

