function setupToertchenPreview() {
  const modal = byId("previewModal");
  if (!modal) return;

  const title = byId("previewTitle");
  const text = byId("previewText");
  const close = byId("previewClose");
  const image = byId("previewImage");
  const triggers = [...document.querySelectorAll("[data-preview]")];

  const palette = [
    "linear-gradient(130deg, #e8c172 0%, #a84f45 100%)",
    "linear-gradient(130deg, #f3d794 0%, #6a3128 100%)",
    "linear-gradient(130deg, #f8d6a0 0%, #9d4e3f 100%)",
    "linear-gradient(130deg, #d8c6aa 0%, #7b3f35 100%)"
  ];

  const open = (el) => {
    const isEn = currentLanguage === "en";
    const titleValue = isEn ? el.getAttribute("data-title-en") : el.getAttribute("data-title");
    const textValue = isEn ? el.getAttribute("data-text-en") : el.getAttribute("data-text");
    title.textContent = titleValue || el.getAttribute("data-title") || "Toertchen";
    text.textContent = textValue || el.getAttribute("data-text") || "";
    const imageSrc = el.getAttribute("data-image");
    if (imageSrc) {
      image.style.backgroundImage = "url(\"" + imageSrc + "\")";
      image.style.backgroundSize = "cover";
      image.style.backgroundPosition = "center";
      image.style.backgroundRepeat = "no-repeat";
      image.style.backgroundColor = "";
    } else {
      const index = Number(el.getAttribute("data-color") || 0);
      image.style.backgroundImage = "none";
      image.style.background = palette[index % palette.length];
      image.style.backgroundSize = "";
      image.style.backgroundPosition = "";
      image.style.backgroundRepeat = "";
    }
    modal.classList.add("open");
    modal.setAttribute("aria-hidden", "false");
    document.body.style.overflow = "hidden";
  };

  const closeModal = () => {
    modal.classList.remove("open");
    modal.setAttribute("aria-hidden", "true");
    document.body.style.overflow = "";
  };

  triggers.forEach((trigger) => {
    trigger.addEventListener("click", () => {
      open(trigger);
      const hash = trigger.getAttribute("data-preview");
      if (hash) history.replaceState(null, "", "#" + hash);
    });
  });

  if (close) close.addEventListener("click", closeModal);
  modal.addEventListener("click", (event) => {
    if (event.target === modal) closeModal();
  });

  const hash = location.hash.replace("#", "");
  if (hash) {
    const target = triggers.find((item) => item.getAttribute("data-preview") === hash);
    if (target) open(target);
  }
}

function hoursOrDate(isoString) {
  const now = new Date();
  const date = new Date(isoString);
  const diff = now.getTime() - date.getTime();
  const locale = currentLanguage === "en" ? "en-GB" : "de-DE";
  if (!Number.isFinite(diff) || diff < 0) return date.toLocaleDateString(locale);

  const hours = Math.floor(diff / (1000 * 60 * 60));
  if (hours <= 23) {
    return currentLanguage === "en" ? hours + "h ago" : "vor " + hours + "h";
  }

  return date.toLocaleDateString(locale);
}

function getTranslatedBlogPost(post) {
  if (currentLanguage !== "en") return post;
  const item = blogTranslationsEn[post.slug];
  if (!item) return post;

  return {
    ...post,
    title: item.title || post.title,
    description: item.description || post.description,
    html: item.html || post.html
  };
}

async function renderBlogList() {
  const host = byId("blogList");
  const moreBtn = byId("blogMoreBtn");
  if (!host) return;

  try {
    const res = await fetch("data/blog-posts.json");
    const postsRaw = await res.json();
    const posts = postsRaw.map(getTranslatedBlogPost);

    host.innerHTML = posts
      .slice(0, blogVisibleCount)
      .map((post) => {
        return (
          '<article class="card blog-item reveal">' +
          '<div class="thumb"><img src="' + post.image + '" alt="' + post.title + '"></div>' +
          '<div class="blog-copy">' +
          "<h3>" + post.title + "</h3>" +
          "<p>" + post.description + "</p>" +
          "</div>" +
          '<div class="blog-side">' +
          '<span class="blog-meta">' + hoursOrDate(post.postedAt) + "</span>" +
          '<a class="btn btn-secondary" href="blog-posts.html#/' + post.slug + '">' + t("blog_read_btn") + "</a>" +
          "</div>" +
          "</article>"
        );
      })
      .join("");

    if (moreBtn) {
      moreBtn.style.display = blogVisibleCount < posts.length ? "inline-flex" : "none";
      moreBtn.onclick = () => {
        blogVisibleCount += 10;
        renderBlogList();
      };
    }

    setupReveal();
  } catch (_err) {
    host.innerHTML = '<article class="card"><p>' + t("blog_empty") + "</p></article>";
    if (moreBtn) moreBtn.style.display = "none";
  }
}

async function renderBlogHtmlOnly() {
  const host = byId("blogRawHtml");
  if (!host) return;

  const slug = location.hash.replace("#/", "");
  if (!slug) {
    host.innerHTML = "<p>" + t("blog_select") + "</p>";
    return;
  }

  try {
    const res = await fetch("data/blog-posts.json");
    const postsRaw = await res.json();
    const posts = postsRaw.map(getTranslatedBlogPost);
    const post = posts.find((item) => item.slug === slug);

    if (!post || !post.html) {
      host.innerHTML = "<p>" + t("blog_notfound") + "</p>";
      return;
    }

    host.innerHTML = post.html;
  } catch (_err) {
    host.innerHTML = "<p>" + t("blog_unavailable") + "</p>";
  }
}

