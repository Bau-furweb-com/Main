function idSelector(name) {
  const safe = String(name).replace(/"/g, '\\"');
  const lower = safe.toLowerCase();
  return `[id="${safe}"], [id^="${safe}-"], [id^="${lower}-"]`;
}

function byId(name) {
  return document.querySelector(idSelector(name));
}

function oneOf(selectors) {
  for (const sel of selectors) {
    const node = document.querySelector(sel);
    if (node) return node;
  }
  return null;
}

function setupMenu() {
  const toggle = oneOf([idSelector("menuToggle"), ".menu-toggle"]);
  const nav = oneOf([idSelector("siteNav"), "header .site-nav"]);
  if (!toggle || !nav) return;

  if (!toggle.querySelector(".menu-toggle-lines")) {
    const lines = document.createElement("span");
    lines.className = "menu-toggle-lines";
    lines.innerHTML = "<span></span><span></span><span></span>";
    toggle.textContent = "";
    toggle.appendChild(lines);
  }

  toggle.setAttribute("aria-expanded", "false");
  toggle.setAttribute("aria-label", "Open menu");

  let overlay = byId("mobileMenuOverlay");
  if (!overlay) {
    overlay = document.createElement("div");
    overlay.id = "mobileMenuOverlay";
    overlay.className = "mobile-overlay";
    overlay.setAttribute("aria-hidden", "true");

    const panel = document.createElement("div");
    panel.className = "mobile-panel";

    const mobileNav = nav.cloneNode(true);
    mobileNav.id = "mobileNav";
    mobileNav.className = "mobile-nav";
    mobileNav.querySelectorAll("a").forEach((link) => {
      link.addEventListener("click", () => closeMenu());
    });

    panel.appendChild(mobileNav);

    const desktopLangSwitch = document.querySelector(".header-inner > .lang-switch");
    if (desktopLangSwitch) {
      const mobileLangSwitch = desktopLangSwitch.cloneNode(true);
      mobileLangSwitch.classList.add("mobile-lang");
      panel.appendChild(mobileLangSwitch);
    }

    overlay.appendChild(panel);
    document.body.appendChild(overlay);
  }

  const closeMenu = () => {
    document.body.classList.remove("menu-open");
    toggle.setAttribute("aria-expanded", "false");
    overlay.setAttribute("aria-hidden", "true");
  };

  const openMenu = () => {
    document.body.classList.add("menu-open");
    toggle.setAttribute("aria-expanded", "true");
    overlay.setAttribute("aria-hidden", "false");
  };

  toggle.addEventListener("click", () => {
    if (document.body.classList.contains("menu-open")) closeMenu();
    else openMenu();
  });

  overlay.addEventListener("click", (event) => {
    if (event.target === overlay) closeMenu();
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeMenu();
  });

  window.addEventListener("resize", () => {
    if (window.innerWidth > 760) closeMenu();
  });

  nav.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      nav.classList.remove("open");
      closeMenu();
    });
  });
}

function setupHeaderAndHeroScroll() {
  const header = document.querySelector(".site-header");
  const isHome = document.body.dataset.page === "home";

  const onScroll = () => {
    const y = window.scrollY;
    if (header) header.classList.toggle("scrolled", y > 50);
    if (isHome) {
      const progress = Math.max(0, Math.min(y / 210, 1));
      document.body.style.setProperty("--hero-progress", progress.toFixed(4));
    }
  };

  onScroll();
  window.addEventListener("scroll", onScroll, { passive: true });
}

